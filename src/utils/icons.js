/**
 * Render all `[data-lucide]` icons in the document.
 */
export function refreshIcons() {
  createIcons({
    icons: appIcons,
    nameAttr: 'data-lucide',
    attrs: {
      'stroke-width': 2,
    },
  });
}

/** Compatibility shim for legacy `lucide.createIcons()` call sites. */
if (typeof window !== 'undefined') {
  window.lucide = {
    createIcons: refreshIcons,
  };
}
